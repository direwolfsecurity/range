#!/usr/bin/env bash
# =============================================================================
# set-root-hints-ubuntu.sh  —  Point a downstream Ubuntu recursive resolver at
#                              the cyber range root servers.
#
# Detects and configures whichever is installed:  BIND9 (named)  and/or  Unbound
# Also turns OFF DNSSEC validation — with a private root, the real root trust
# anchor can never validate, so every lookup would SERVFAIL otherwise.
#
# Usage:
#   sudo ./set-root-hints-ubuntu.sh --root1-ip 10.0.0.10 --root2-ip 10.0.0.11
#   sudo ./set-root-hints-ubuntu.sh ... --install bind9     # install a resolver too
#   sudo ./set-root-hints-ubuntu.sh ... --hints-only        # just write the file
#   sudo ./set-root-hints-ubuntu.sh ... --serve 172.16.0.0/12,10.0.0.0/8
#        answer these networks too (a resolver for the whole range).
#        Without --serve, the resolver keeps its default: only this machine.
#
# Do NOT run this on the root servers themselves (it stops if it sees one).
#
# License: GPL-3.0, Dire Wolf Security.
# =============================================================================
set -euo pipefail

# ----------------------------- EDIT THESE ------------------------------------
ROOT1_NAME="a.root-servers.net"
ROOT1_IP=""
ROOT1_IP6=""
ROOT2_NAME="b.root-servers.net"
ROOT2_IP=""
ROOT2_IP6=""
# -----------------------------------------------------------------------------
INSTALL=""
HINTS_ONLY=0
SERVE=""        # comma-separated networks allowed to use this resolver

while [[ $# -gt 0 ]]; do
  case "$1" in
    --root1-name) ROOT1_NAME="$2"; shift 2 ;;
    --root1-ip)   ROOT1_IP="$2";   shift 2 ;;
    --root1-ip6)  ROOT1_IP6="$2";  shift 2 ;;
    --root2-name) ROOT2_NAME="$2"; shift 2 ;;
    --root2-ip)   ROOT2_IP="$2";   shift 2 ;;
    --root2-ip6)  ROOT2_IP6="$2";  shift 2 ;;
    --install)    INSTALL="$2";    shift 2 ;;
    --hints-only) HINTS_ONLY=1;    shift ;;
    --serve)      SERVE="$2";     shift 2 ;;
    -h|--help)    sed -n '2,17p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

log()  { echo -e "\e[1;32m[+]\e[0m $*"; }
warn() { echo -e "\e[1;33m[!]\e[0m $*"; }
die()  { echo -e "\e[1;31m[x]\e[0m $*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "Run as root (sudo)."
[[ -n "$ROOT1_IP" && -n "$ROOT2_IP" ]] || die "Set ROOT1_IP and ROOT2_IP (edit the script or use flags)."

R1="${ROOT1_NAME%.}."; R2="${ROOT2_NAME%.}."

# --serve: turn "a,b" into a list and check each one looks like a network (1.2.3.0/24).
SERVE_NETS=()
if [[ -n "$SERVE" ]]; then
  IFS=',' read -r -a SERVE_NETS <<<"${SERVE// /}"
  for n in "${SERVE_NETS[@]}"; do
    [[ "$n" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] || die "--serve: '$n' is not a network like 172.16.0.0/12"
  done
fi

# A root server answers for "." itself and has no use for root hints.
if grep -qs "Managed by setup-root-dns.sh" /etc/bind/named.conf; then
  die "This machine is a range ROOT server (setup-root-dns.sh). Run this script on the resolvers, not here."
fi
TS=$(date +%Y%m%d-%H%M%S)

# ---- Optional install -------------------------------------------------------
if [[ -n "$INSTALL" ]]; then
  [[ "$INSTALL" == "bind9" || "$INSTALL" == "unbound" ]] || die "--install must be bind9 or unbound"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y || warn "apt-get update failed (offline?)"
  if [[ "$INSTALL" == bind9 ]]; then
    apt-get install -y bind9 bind9-utils bind9-dnsutils
  else
    apt-get install -y unbound bind9-dnsutils
  fi
fi

# ---- Build hints file --------------------------------------------------------
make_hints() {
  cat <<EOF
; Cyber range root hints — generated by set-root-hints-ubuntu.sh ($TS)
; Replaces the Internet root hints. Do NOT let dns-root-data updates overwrite.
.                        3600000      NS    ${R1}
${R1}  3600000      A     ${ROOT1_IP}
EOF
  [[ -n "$ROOT1_IP6" ]] && echo "${R1}  3600000      AAAA  ${ROOT1_IP6}"
  cat <<EOF
.                        3600000      NS    ${R2}
${R2}  3600000      A     ${ROOT2_IP}
EOF
  [[ -n "$ROOT2_IP6" ]] && echo "${R2}  3600000      AAAA  ${ROOT2_IP6}"
  echo "; End of file"
}

HINTS_TMP=$(mktemp); make_hints > "$HINTS_TMP"; chmod 644 "$HINTS_TMP"

if [[ $HINTS_ONLY -eq 1 ]]; then
  install -m 644 "$HINTS_TMP" /etc/range-root.hints
  log "Wrote /etc/range-root.hints"; cat /etc/range-root.hints; exit 0
fi

DID=0

# ---- BIND9 -------------------------------------------------------------------
if command -v named >/dev/null 2>&1 && [[ -d /etc/bind ]]; then
  log "BIND9 detected — configuring root hints"
  mkdir -p /etc/bind/backup-$TS; cp -a /etc/bind/named.conf* /etc/bind/backup-$TS/
  install -m 644 -o root -g bind "$HINTS_TMP" /etc/bind/db.root.range

  # Repoint every hint zone at our file, wherever it is defined
  mapfile -t CONFS < <(grep -lE 'type\s+hint' /etc/bind/named.conf* 2>/dev/null || true)
  if [[ ${#CONFS[@]} -eq 0 ]]; then
    warn "No 'type hint' zone found — adding one to named.conf.local"
    cat >> /etc/bind/named.conf.local <<'EOF'

// Added by set-root-hints-ubuntu.sh
zone "." { type hint; file "/etc/bind/db.root.range"; };
EOF
  else
    for f in "${CONFS[@]}"; do
      # Replace the file "..." inside the zone "." hint block
      perl -0pi -e 's#(zone\s+"\."\s*(?:IN\s*)?\{[^}]*?type\s+hint;[^}]*?file\s+")[^"]+(")#${1}/etc/bind/db.root.range${2}#gs; s#(zone\s+"\."\s*(?:IN\s*)?\{[^}]*?file\s+")[^"]+("[^}]*?type\s+hint;)#${1}/etc/bind/db.root.range${2}#gs' "$f"
      log "  updated hint zone in $f"
    done
  fi

  # Disable DNSSEC validation (Ubuntu default is 'auto' = real root key)
  OPT=/etc/bind/named.conf.options
  if grep -qE '^\s*dnssec-validation' "$OPT"; then
    sed -i -E 's/^(\s*)dnssec-validation\s+[a-z]+;/\1dnssec-validation no;  \/\/ range: private root/' "$OPT"
  else
    sed -i -E '0,/options\s*\{/s//options {\n\tdnssec-validation no;  \/\/ range: private root/' "$OPT"
  fi
  log "  dnssec-validation no"

  if grep -qE '^\s*forwarders\s*\{[^}]*[0-9]' "$OPT"; then
    warn "  forwarders{} are set in $OPT — root hints are only used if forwarding fails."
    warn "  Remove the forwarders block (or add 'forward first;') if you want true recursion."
  fi

  if [[ ${#SERVE_NETS[@]} -gt 0 ]]; then
    # Answer the range, not only this machine. Our own file, so re-runs replace it.
    ACL=/etc/bind/named.conf.range-clients
    { echo "// Generated by set-root-hints-ubuntu.sh --serve"
      echo "acl range_clients { localhost; localnets;"
      for n in "${SERVE_NETS[@]}"; do echo "    $n;"; done
      echo "};"; } > "$ACL"
    grep -q "named.conf.range-clients" /etc/bind/named.conf || echo 'include "/etc/bind/named.conf.range-clients";' >> /etc/bind/named.conf
    sed -i -E '/^\s*(allow-recursion|allow-query-cache|listen-on)\s/d' "$OPT"
    sed -i -E '0,/options\s*\{/s//options {\n\tlisten-on { any; };\n\tallow-recursion { range_clients; };\n\tallow-query-cache { range_clients; };/' "$OPT"
    log "  answers: localhost and ${SERVE_NETS[*]}"
  fi

  named-checkconf || die "named-checkconf failed. Backup in /etc/bind/backup-$TS"
  systemctl restart named
  rndc flush 2>/dev/null || true
  log "  named restarted, cache flushed"
  DID=1
fi

# ---- Unbound -------------------------------------------------------------------
if command -v unbound >/dev/null 2>&1 && [[ -d /etc/unbound ]]; then
  log "Unbound detected — configuring root hints"
  install -m 644 "$HINTS_TMP" /etc/unbound/range-root.hints

  # Ubuntu ships an auto-trust-anchor snippet; it would force validation against
  # the real root key. Park it.
  for f in /etc/unbound/unbound.conf.d/root-auto-trust-anchor*.conf; do
    [[ -f "$f" ]] && mv "$f" "$f.disabled-$TS" && log "  disabled $(basename "$f")"
  done
  # Any other trust-anchor lines in drop-ins
  # "|| true": finding no other trust anchors is normal and must not stop the script (set -e).
  { grep -lE '^\s*(auto-)?trust-anchor' /etc/unbound/unbound.conf.d/*.conf 2>/dev/null || true; } | while read -r f; do
    sed -i -E 's/^(\s*)((auto-)?trust-anchor)/\1# range-disabled: \2/' "$f"; log "  commented trust anchors in $f"
  done

  cat > /etc/unbound/unbound.conf.d/zz-range-root.conf <<'EOF'
# Generated by set-root-hints-ubuntu.sh — cyber range private root
server:
    root-hints: "/etc/unbound/range-root.hints"
    module-config: "iterator"        # no validator: private root can't validate
    harden-referral-path: no
EOF
  if [[ ${#SERVE_NETS[@]} -gt 0 ]]; then
    # Answer the range, not only this machine.
    { echo "    interface: 0.0.0.0"
      echo "    access-control: 127.0.0.0/8 allow"
      for n in "${SERVE_NETS[@]}"; do echo "    access-control: $n allow"; done; } >> /etc/unbound/unbound.conf.d/zz-range-root.conf
    log "  answers: localhost and ${SERVE_NETS[*]}"
  fi
  unbound-checkconf || die "unbound-checkconf failed"
  systemctl restart unbound
  log "  unbound restarted"
  DID=1
fi

rm -f "$HINTS_TMP"

if [[ $DID -eq 0 ]]; then
  warn "No BIND9 or Unbound resolver found. Root hints only matter on a recursive resolver."
  warn "Re-run with  --install bind9  (or unbound), or --hints-only to just write the file."
  exit 2
fi

# ---- Quick test ------------------------------------------------------------------
if command -v dig >/dev/null; then
  log "Test: asking local resolver for the root NS set"
  dig +short @127.0.0.1 . NS || true
  echo "If you see ${R1} / ${R2} above, recursion is using the range root."
fi
